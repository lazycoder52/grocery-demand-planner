log = logging.getLogger("demand_planner.simulation")


@dataclass
class SimConfig:
    """Configuration parameters for periodic-review replenishment simulation."""

    seed: int = 42
    review_period_days: int = 7
    lead_times_days: tuple[int, ...] = (3, 7, 14)
    service_levels: tuple[float, ...] = (0.90, 0.95, 0.98)
    warmup_days: int = 14
    z_grid: tuple[float, ...] = (
        0.0,
        0.25,
        0.5,
        0.75,
        1.0,
        1.25,
        1.282,
        1.5,
        1.645,
        1.75,
        2.0,
        2.054,
        2.25,
        2.5,
        3.0,
        3.5,
    )

    @classmethod
    def from_yaml(cls, path: Path | str = "config/sim_config.yaml") -> SimConfig:
        """Load configuration from a YAML file."""
        p = Path(path)
        if not p.exists():
            log.warning("Config file %s not found; using default parameters", path)
            return cls()
        with open(p, encoding="utf-8") as f:
            raw = yaml.safe_load(f) or {}
        z_raw = raw.get("z_grid", None)
        z_grid_val = tuple(float(x) for x in z_raw) if z_raw is not None else cls.z_grid
        return cls(
            seed=int(raw.get("seed", 42)),
            review_period_days=int(raw.get("review_period_days", 7)),
            lead_times_days=tuple(int(x) for x in raw.get("lead_times_days", [3, 7, 14])),
            service_levels=tuple(float(x) for x in raw.get("service_levels", [0.90, 0.95, 0.98])),
            warmup_days=int(raw.get("warmup_days", 14)),
            z_grid=z_grid_val,
        )


class PeriodicReviewSimulator:
    """Simulates periodic-review (R, S) order-up-to inventory replenishment.

    Parameters
    ----------
    df_predictions : pd.DataFrame
        DataFrame containing out-of-fold and holdout predictions. Must contain:
        ['date', 'store_nbr', 'family', 'sales', 'pred_lgbm', 'pred_snaive',
         'pred_p10', 'pred_p50', 'pred_p90'].
        May optionally contain 'sigma_lgbm' and 'sigma_snaive' containing strictly
        pre-origin empirical residual standard deviations.
    config : SimConfig | None
        Simulation configuration.
    review_forecasts_df : pd.DataFrame | None
        Optional DataFrame containing per-review-date forecasts and pre-origin sigmas
        generated by generate_review_forecasts.
    stitching_rule : str
        Stitching mode: 'reforecast' (default, per-review-date origin=t forecasts without scaling),
        'clamped_scaled' (boundary clamped and scaled run-rates), or
        'inside_fold_only' (only place orders whose full protection window fits inside the fold).
    """

    def __init__(
        self,
        df_predictions: pd.DataFrame,
        config: SimConfig | None = None,
        review_forecasts_df: pd.DataFrame | None = None,
        stitching_rule: str = "reforecast",
    ) -> None:
        self.config = config or SimConfig()
        self.rng = np.random.default_rng(self.config.seed)
        self.stitching_rule = stitching_rule

        df = df_predictions.copy()
        df["date"] = pd.to_datetime(df["date"])
        df = df.sort_values(["store_nbr", "family", "date"]).reset_index(drop=True)

        self.dates = sorted(df["date"].unique())
        self.n_days = len(self.dates)
        date_map = {d: i for i, d in enumerate(self.dates)}
        df["day_idx"] = df["date"].map(date_map)

        self.series_keys = df[["store_nbr", "family"]].drop_duplicates().reset_index(drop=True)
        self.n_series = len(self.series_keys)

        # Pre-pivot to 2D numpy arrays of shape (n_series, n_days)
        self.sales = df.pivot(
            index=["store_nbr", "family"], columns="day_idx", values="sales"
        ).to_numpy(dtype=np.float32)
        self.pred_snaive = df.pivot(
            index=["store_nbr", "family"], columns="day_idx", values="pred_snaive"
        ).to_numpy(dtype=np.float32)
        self.pred_p50 = df.pivot(
            index=["store_nbr", "family"], columns="day_idx", values="pred_p50"
        ).to_numpy(dtype=np.float32)
        self.pred_p90 = df.pivot(
            index=["store_nbr", "family"], columns="day_idx", values="pred_p90"
        ).to_numpy(dtype=np.float32)

        # LightGBM point model predictions (L2 conditional mean)
        if "pred_lgbm" in df.columns:
            self.pred_point = df.pivot(
                index=["store_nbr", "family"], columns="day_idx", values="pred_lgbm"
            ).to_numpy(dtype=np.float32)
        else:
            self.pred_point = self.pred_p50.copy()

        # Map each day to the end of its active fold to prevent future-fold model leakage
        if "split" in df.columns:
            split_max_day = df.groupby("split", observed=False)["day_idx"].max().to_dict()
            day_split = df.groupby("day_idx")["split"].first().to_dict()
            self.active_fold_end_idx = np.array(
                [split_max_day[day_split[i]] for i in range(self.n_days)], dtype=int
            )
        else:
            self.active_fold_end_idx = np.full(self.n_days, self.n_days - 1, dtype=int)

        # Pre-origin empirical residual standard deviations (strictly date <= split.origin_date)
        if "sigma_lgbm" in df.columns:
            self.sigma_lgbm = df.pivot(
                index=["store_nbr", "family"], columns="day_idx", values="sigma_lgbm"
            ).to_numpy(dtype=np.float32)
        else:
            # Fallback for standalone mock test fixtures
            res_l = self.sales - self.pred_p50
            self.sigma_lgbm = np.repeat(
                np.std(res_l[:, : min(7, self.n_days)], axis=1, keepdims=True),
                self.n_days,
                axis=1,
            ).astype(np.float32)

        if "sigma_snaive" in df.columns:
            self.sigma_snaive = df.pivot(
                index=["store_nbr", "family"], columns="day_idx", values="sigma_snaive"
            ).to_numpy(dtype=np.float32)
        else:
            res_s = self.sales - self.pred_snaive
            self.sigma_snaive = np.repeat(
                np.std(res_s[:, : min(7, self.n_days)], axis=1, keepdims=True),
                self.n_days,
                axis=1,
            ).astype(np.float32)

        # Review-date forecasts and pre-origin sigmas (Rule 2: per-review-date re-forecasting)
        self.review_fc: dict[tuple[int, str], np.ndarray] = {}
        self.review_sig: dict[tuple[int, str], np.ndarray] = {}
        self.review_fc_days: set[int] = set()

        if review_forecasts_df is not None and len(review_forecasts_df) > 0:
            rf = review_forecasts_df.copy()
            unique_t = sorted(rf["review_day_idx"].unique())
            self.review_fc_days = set(int(t) for t in unique_t)
            multi_idx = pd.MultiIndex.from_frame(self.series_keys)

            for t_val in unique_t:
                sub_t = rf[rf["review_day_idx"] == t_val]
                p_pt = (
                    sub_t.pivot(
                        index=["store_nbr", "family"], columns="horizon_step", values="pred_lgbm"
                    )
                    .reindex(index=multi_idx)
                    .fillna(0.0)
                    .to_numpy(dtype=np.float32)
                )
                p_p50 = (
                    sub_t.pivot(
                        index=["store_nbr", "family"], columns="horizon_step", values="pred_p50"
                    )
                    .reindex(index=multi_idx)
                    .fillna(0.0)
                    .to_numpy(dtype=np.float32)
                )
                p_sn = (
                    sub_t.pivot(
                        index=["store_nbr", "family"], columns="horizon_step", values="pred_snaive"
                    )
                    .reindex(index=multi_idx)
                    .fillna(0.0)
                    .to_numpy(dtype=np.float32)
                )

                self.review_fc[(int(t_val), "point")] = p_pt
                self.review_fc[(int(t_val), "p50")] = p_p50
                self.review_fc[(int(t_val), "snaive")] = p_sn

                sig_l_val = (
                    sub_t.groupby(["store_nbr", "family"], observed=False)["sigma_lgbm"]
                    .first()
                    .reindex(multi_idx)
                    .fillna(0.0)
                    .to_numpy(dtype=np.float32)
                )
                sig_sn_val = (
                    sub_t.groupby(["store_nbr", "family"], observed=False)["sigma_snaive"]
                    .first()
                    .reindex(multi_idx)
                    .fillna(0.0)
                    .to_numpy(dtype=np.float32)
                )
                self.review_sig[(int(t_val), "lgbm")] = sig_l_val
                self.review_sig[(int(t_val), "snaive")] = sig_sn_val

    def _get_forecast(
        self,
        policy_name: str,
        t: int,
        protection_days: int,
    ) -> np.ndarray:
        """Sum forecasted demand over protection interval [t, t + protection_days].

        Strictly clamps the forecast slice to the end of the active fold containing day t
        so that no future-fold models (whose origin date > order date) can be accessed.
        If the protection window exceeds the remaining days of the active fold, the available
        causal forecast is scaled proportionally over the full protection window.
        """
        fold_end = self.active_fold_end_idx[t]
        end = min(t + protection_days, fold_end + 1, self.n_days)
        obs_days = max(end - t, 1)

        if "seasonal_naive" in policy_name:
            fc = self.pred_snaive[:, t:end]
        elif "point" in policy_name or "pred_lgbm" in policy_name:
            fc = self.pred_point[:, t:end]
        elif policy_name == "summed_p90":
            fc = self.pred_p90[:, t:end]
        else:  # lightgbm_p50 or lightgbm_p50_safety_stock
            fc = self.pred_p50[:, t:end]

        summed = fc.sum(axis=1)
        if obs_days < protection_days:
            summed = summed * (protection_days / obs_days)

        return summed

    def simulate_policy(
        self,
        policy: str,
        lead_time_days: int,
        service_level: float | None = None,
        z_value: float | None = None,
        return_series_metrics: bool = False,
    ) -> dict[str, Any]:
        """Execute a single replenishment simulation run across all series."""
        L = lead_time_days
        R = self.config.review_period_days
        protection_days = R + L

        # Calculate safety stock factor z
        z = 0.0
        if "safety_stock" in policy:
            if z_value is not None:
                z = float(z_value)
            elif service_level is not None:
                z = float(norm.ppf(service_level))
            else:
                z = float(norm.ppf(0.95))

        # Select pre-origin calibrated residual standard deviation matrix
        if ("lightgbm" in policy or "point" in policy) and "safety_stock" in policy:
            sig_mat = self.sigma_lgbm
        elif "seasonal_naive" in policy and "safety_stock" in policy:
            sig_mat = self.sigma_snaive
        else:
            sig_mat = np.zeros_like(self.sales)

        # Initial inventory warm-start: S_0 = D_hat(0, R+L) + SS_0
        if self.stitching_rule == "reforecast" and 0 in self.review_fc_days:
            pol_key = (
                "snaive"
                if "seasonal_naive" in policy
                else ("point" if "point" in policy or "pred_lgbm" in policy else "p50")
            )
            sig_key = "snaive" if "seasonal_naive" in policy else "lgbm"
            D_0 = self.review_fc[(0, pol_key)][:, :protection_days].sum(axis=1)
            sig_0 = (
                self.review_sig[(0, sig_key)]
                if "safety_stock" in policy
                else np.zeros(self.n_series, dtype=np.float32)
            )
            SS_0 = np.maximum(0.0, z * sig_0 * np.sqrt(protection_days)).astype(np.float32)
            S_0 = D_0 + SS_0
        else:
            SS_0 = np.maximum(0.0, z * sig_mat[:, 0] * np.sqrt(protection_days)).astype(np.float32)
            S_0 = self._get_forecast(policy, 0, protection_days) + SS_0
        on_hand = S_0.copy()

        # Inflow pipeline dictionary: arrival_day -> order_quantities_array
        pipeline_orders: dict[int, np.ndarray] = {}

        # Warm-up handling: exclude first warmup_days from metric accumulation
        eval_start = min(self.config.warmup_days, self.n_days - 1)
        eval_days = self.n_days - eval_start

        total_sales = 0.0
        total_demand = 0.0
        stockout_series_days = 0
        inventory_sum = 0.0

        # Per-series arrays for bootstrap and family breakdown
        series_sales = np.zeros(self.n_series, dtype=np.float64)
        series_demand = np.zeros(self.n_series, dtype=np.float64)
        series_inv_sum = np.zeros(self.n_series, dtype=np.float64)
        series_stockouts = np.zeros(self.n_series, dtype=np.int32)

        # Weekly time-block arrays for time-block bootstrap
        n_weeks = max(1, int(np.ceil(eval_days / 7.0)))
        week_sales = np.zeros(n_weeks, dtype=np.float64)
        week_demand = np.zeros(n_weeks, dtype=np.float64)
        week_inv_sum = np.zeros(n_weeks, dtype=np.float64)
        week_days = np.zeros(n_weeks, dtype=np.float64)

        # Per-series weekly arrays for per-family time-block bootstrap
        series_week_sales = np.zeros((self.n_series, n_weeks), dtype=np.float64)
        series_week_demand = np.zeros((self.n_series, n_weeks), dtype=np.float64)
        series_week_inv = np.zeros((self.n_series, n_weeks), dtype=np.float64)

        for t in range(self.n_days):
            # 1. Receive incoming shipments placed at t - L
            if t in pipeline_orders:
                on_hand += pipeline_orders[t]
                del pipeline_orders[t]

            # 2. Satisfy daily demand (censored by physical on-hand stock)
            d_t = self.sales[:, t]
            fulfilled = np.minimum(on_hand, d_t)
            unmet = d_t - fulfilled

            if t >= eval_start:
                total_sales += float(fulfilled.sum())
                total_demand += float(d_t.sum())
                stockout_series_days += int(np.count_nonzero(unmet > 1e-4))

                series_sales += fulfilled.astype(np.float64)
                series_demand += d_t.astype(np.float64)
                series_stockouts += (unmet > 1e-4).astype(np.int32)

                w_idx = min((t - eval_start) // 7, n_weeks - 1)
                week_sales[w_idx] += float(fulfilled.sum())
                week_demand[w_idx] += float(d_t.sum())
                series_week_sales[:, w_idx] += fulfilled.astype(np.float64)
                series_week_demand[:, w_idx] += d_t.astype(np.float64)

            # Deduct sold inventory; on-hand is never negative
            on_hand -= fulfilled
            if t >= eval_start:
                inventory_sum += float(on_hand.sum())
                series_inv_sum += on_hand.astype(np.float64)
                w_idx = min((t - eval_start) // 7, n_weeks - 1)
                week_inv_sum[w_idx] += float(on_hand.sum())
                week_days[w_idx] += 1.0
                series_week_inv[:, w_idx] += on_hand.astype(np.float64)

            # 3. Periodic review order placement on review days (t % R == 0)
            if t % R == 0:
                fold_end = self.active_fold_end_idx[t]
                # Rule 3: inside_fold_only skips orders when full protection window exceeds fold end
                if self.stitching_rule == "inside_fold_only" and (t + protection_days) > (
                    fold_end + 1
                ):
                    pass
                else:
                    in_transit = sum(
                        orders for arr_day, orders in pipeline_orders.items() if arr_day > t
                    )
                    inventory_position = on_hand + in_transit

                    if self.stitching_rule == "reforecast" and t in self.review_fc_days:
                        pol_key = (
                            "snaive"
                            if "seasonal_naive" in policy
                            else ("point" if "point" in policy or "pred_lgbm" in policy else "p50")
                        )
                        sig_key = "snaive" if "seasonal_naive" in policy else "lgbm"
                        fc_t = self.review_fc[(t, pol_key)][:, :protection_days].sum(axis=1)
                        sig_t = (
                            self.review_sig[(t, sig_key)]
                            if "safety_stock" in policy
                            else np.zeros(self.n_series, dtype=np.float32)
                        )
                        SS_t = np.maximum(0.0, z * sig_t * np.sqrt(protection_days)).astype(
                            np.float32
                        )
                        S_t = fc_t + SS_t
                    else:
                        SS_t = np.maximum(0.0, z * sig_mat[:, t] * np.sqrt(protection_days)).astype(
                            np.float32
                        )
                        S_t = self._get_forecast(policy, t, protection_days) + SS_t

                    order_qty = np.maximum(0.0, S_t - inventory_position)

                    arrival_day = t + L
                    if arrival_day not in pipeline_orders:
                        pipeline_orders[arrival_day] = order_qty.copy()
                    else:
                        pipeline_orders[arrival_day] += order_qty

        fill_rate_pct = 100.0 if total_demand == 0.0 else (total_sales / total_demand) * 100.0
        stockout_share_pct = (stockout_series_days / (self.n_series * eval_days)) * 100.0
        avg_inventory = inventory_sum / eval_days
        annualized_sales = total_sales * (365.0 / eval_days)
        turns = annualized_sales / max(avg_inventory, 1e-6)

        is_sensitivity = L == 14
        policy_label = policy
        if "safety_stock" in policy:
            if "point" in policy:
                label_prefix = "LightGBM Point + SS"
            elif "lightgbm" in policy:
                label_prefix = "LightGBM P50 + SS"
            else:
                label_prefix = "Seasonal Naive + SS"
            if service_level is not None:
                sl_pct = int(round(service_level * 100))
                policy_label = f"{label_prefix} ({sl_pct}%)"
            else:
                policy_label = f"{label_prefix} (z={z:.2f})"
        elif policy == "summed_p90":
            policy_label = "Summed Daily P90 (Conservative Upper Bound)"
        elif policy == "lightgbm_p50":
            policy_label = "LightGBM P50"
        elif policy in ("lightgbm_point", "point"):
            policy_label = "LightGBM Point"
        elif policy == "seasonal_naive":
            policy_label = "Seasonal Naive (7-Day)"

        out: dict[str, Any] = {
            "policy": policy,
            "policy_label": policy_label,
            "stitching_rule": self.stitching_rule,
            "lead_time_days": L,
            "is_sensitivity_extrapolation": is_sensitivity,
            "service_level": service_level if "safety_stock" in policy else None,
            "z_value": z if "safety_stock" in policy else 0.0,
            "fill_rate_pct": float(round(fill_rate_pct, 2)),
            "stockout_day_share_pct": float(round(stockout_share_pct, 2)),
            "average_inventory_units": float(round(avg_inventory, 2)),
            "inventory_turns": float(round(turns, 2)),
            "inventory_turns_note": (
                "Idealized metric under continuous fractional ordering without "
                "case packs, MOQs, or warehouse dispatch constraints."
            ),
            "total_sales_units": float(round(total_sales, 2)),
            "total_demand_units": float(round(total_demand, 2)),
            "simulation_days": self.n_days,
            "evaluated_days": eval_days,
            "warmup_days_excluded": eval_start,
            "n_store_families": self.n_series,
        }

        if return_series_metrics:
            out["series_metrics"] = {
                "sales": series_sales,
                "demand": series_demand,
                "inv_sum": series_inv_sum,
                "stockouts": series_stockouts,
                "eval_days": eval_days,
                "week_sales": week_sales,
                "week_demand": week_demand,
                "week_inv_sum": week_inv_sum,
                "week_days": week_days,
                "series_week_sales": series_week_sales,
                "series_week_demand": series_week_demand,
                "series_week_inv": series_week_inv,
                "n_weeks": n_weeks,
            }

        return out

    def run_all_simulations(self) -> pd.DataFrame:
        """Run standard configured policies across lead times and return summary DataFrame."""
        records: list[dict[str, Any]] = []

        for L in self.config.lead_times_days:
            # 1. Seasonal Naive point
            records.append(self.simulate_policy("seasonal_naive", lead_time_days=L))

            # 2. LightGBM P50 point
            records.append(self.simulate_policy("lightgbm_p50", lead_time_days=L))

            # 3. LightGBM Point model
            records.append(self.simulate_policy("lightgbm_point", lead_time_days=L))

            # 4. LightGBM P50 + Safety Stock
            for sl in self.config.service_levels:
                records.append(
                    self.simulate_policy(
                        "lightgbm_p50_safety_stock", lead_time_days=L, service_level=sl
                    )
                )

            # 5. LightGBM Point + Safety Stock
            for sl in self.config.service_levels:
                records.append(
                    self.simulate_policy(
                        "lightgbm_point_safety_stock", lead_time_days=L, service_level=sl
                    )
                )

            # 6. Seasonal Naive + Safety Stock (matched service levels)
            for sl in self.config.service_levels:
                records.append(
                    self.simulate_policy(
                        "seasonal_naive_safety_stock", lead_time_days=L, service_level=sl
                    )
                )

            # 7. Summed daily P90
            records.append(self.simulate_policy("summed_p90", lead_time_days=L))

        return pd.DataFrame(records)

    def run_frontier(
        self,
        lead_times: tuple[int, ...] = (3, 7),
        z_values: tuple[float, ...] | None = None,
    ) -> pd.DataFrame:
        """Trace the fill-rate vs average-inventory frontier over a fine z grid."""
        grid = z_values or self.config.z_grid
        records: list[dict[str, Any]] = []

        for L in lead_times:
            for z in grid:
                res_p50 = self.simulate_policy(
                    "lightgbm_p50_safety_stock",
                    lead_time_days=L,
                    z_value=z,
                    return_series_metrics=True,
                )
                res_point = self.simulate_policy(
                    "lightgbm_point_safety_stock",
                    lead_time_days=L,
                    z_value=z,
                    return_series_metrics=True,
                )
                res_snaive = self.simulate_policy(
                    "seasonal_naive_safety_stock",
                    lead_time_days=L,
                    z_value=z,
                    return_series_metrics=True,
                )
                records.append(res_p50)
                records.append(res_point)
                records.append(res_snaive)

        return pd.DataFrame(records)

    def compute_target_fill_rate_tradeoff(
        self,
        frontier_df: pd.DataFrame,
        target_fill_rates: tuple[float, ...] = (98.5, 99.0, 99.5),
        n_bootstrap: int = 1000,
        lead_times: tuple[int, ...] = (3, 7),
        seed: int = 42,
    ) -> list[dict[str, Any]]:
        """Interpolate required inventory to reach target fill rates with dual bootstrap CIs.

        Computes:
        1. Series bootstrap 95% CIs (cross-sectional resampling of store-family series).
        2. Time-block bootstrap 95% CIs (temporal resampling of weekly review periods).
        Evaluates both LightGBM P50 + SS and LightGBM Point + SS against Seasonal Naive + SS.
        """
        rng = np.random.default_rng(seed)
        results: list[dict[str, Any]] = []

        for L in lead_times:
            df_l = frontier_df[frontier_df["lead_time_days"] == L]

            df_snaive = df_l[df_l["policy"] == "seasonal_naive_safety_stock"].sort_values(
                "fill_rate_pct"
            )
            fr_snaive = df_snaive["fill_rate_pct"].to_numpy()
            inv_snaive = df_snaive["average_inventory_units"].to_numpy()
            series_data_snaive = [row["series_metrics"] for _, row in df_snaive.iterrows()]
            n_weeks = series_data_snaive[0]["n_weeks"]

            models_to_compare = [
                ("lightgbm_p50_safety_stock", "LightGBM P50"),
                ("lightgbm_point_safety_stock", "LightGBM Point"),
            ]

            for model_policy, model_label in models_to_compare:
                df_model = df_l[df_l["policy"] == model_policy].sort_values("fill_rate_pct")
                fr_model = df_model["fill_rate_pct"].to_numpy()
                inv_model = df_model["average_inventory_units"].to_numpy()
                series_data_model = [row["series_metrics"] for _, row in df_model.iterrows()]

                min_fr_model, max_fr_model = float(fr_model[0]), float(fr_model[-1])
                min_fr_sn, max_fr_sn = float(fr_snaive[0]), float(fr_snaive[-1])

                for target_fr in target_fill_rates:
                    is_reachable_model = min_fr_model <= target_fr <= max_fr_model
                    is_reachable_sn = min_fr_sn <= target_fr <= max_fr_sn
                    is_reachable = is_reachable_model and is_reachable_sn

                    if not is_reachable:
                        results.append(
                            {
                                "lead_time_days": L,
                                "comparison": f"{model_label} vs Seasonal Naive",
                                "forecaster": model_label,
                                "target_fill_rate_pct": target_fr,
                                "is_reachable": False,
                                "required_inventory_lightgbm": None,
                                "required_inventory_snaive": None,
                                "pct_difference": None,
                                "ci_95_series_pct_diff_low": None,
                                "ci_95_series_pct_diff_high": None,
                                "ci_95_time_block_pct_diff_low": None,
                                "ci_95_time_block_pct_diff_high": None,
                                "is_within_noise_series": None,
                                "is_within_noise_time_block": None,
                                "model_grid_range_pct": (
                                    round(min_fr_model, 2),
                                    round(max_fr_model, 2),
                                ),
                                "snaive_grid_range_pct": (round(min_fr_sn, 2), round(max_fr_sn, 2)),
                                "interpretation": (
                                    f"Target {target_fr}% unreachable on empirical grid "
                                    f"({model_label} [{min_fr_model:.2f}%, {max_fr_model:.2f}%], "
                                    f"S.Naive [{min_fr_sn:.2f}%, {max_fr_sn:.2f}%])"
                                ),
                            }
                        )
                        continue

                    # Point interpolation along aggregate frontiers
                    idx_m = np.argsort(fr_model)
                    idx_s = np.argsort(fr_snaive)
                    interp_m = interp1d(fr_model[idx_m], inv_model[idx_m])
                    interp_s = interp1d(fr_snaive[idx_s], inv_snaive[idx_s])

                    req_inv_m = float(interp_m(target_fr))
                    req_inv_sn = float(interp_s(target_fr))
                    pct_diff = ((req_inv_m - req_inv_sn) / max(req_inv_sn, 1e-6)) * 100.0

                    # 1. Series Bootstrap (resample store-family series)
                    boot_diffs_series: list[float] = []
                    for _ in range(n_bootstrap):
                        idx = rng.integers(0, self.n_series, size=self.n_series)

                        b_fr_m, b_inv_m = [], []
                        for m in series_data_model:
                            s = m["sales"][idx].sum()
                            d = m["demand"][idx].sum()
                            b_fr_m.append((s / max(d, 1e-6)) * 100.0)
                            b_inv_m.append(m["inv_sum"][idx].sum() / m["eval_days"])

                        b_fr_s, b_inv_s = [], []
                        for m in series_data_snaive:
                            s = m["sales"][idx].sum()
                            d = m["demand"][idx].sum()
                            b_fr_s.append((s / max(d, 1e-6)) * 100.0)
                            b_inv_s.append(m["inv_sum"][idx].sum() / m["eval_days"])

                        if min(b_fr_m) <= target_fr <= max(b_fr_m) and min(
                            b_fr_s
                        ) <= target_fr <= max(b_fr_s):
                            im = np.argsort(b_fr_m)
                            is_ = np.argsort(b_fr_s)
                            bf_m = interp1d(np.array(b_fr_m)[im], np.array(b_inv_m)[im])
                            bf_s = interp1d(np.array(b_fr_s)[is_], np.array(b_inv_s)[is_])
                            b_diff = (
                                (float(bf_m(target_fr)) - float(bf_s(target_fr)))
                                / max(float(bf_s(target_fr)), 1e-6)
                            ) * 100.0
                            boot_diffs_series.append(b_diff)

                    if len(boot_diffs_series) >= 20:
                        ci_ser_low = float(np.percentile(boot_diffs_series, 2.5))
                        ci_ser_high = float(np.percentile(boot_diffs_series, 97.5))
                        is_within_noise_ser = ci_ser_low <= 0.0 <= ci_ser_high
                    else:
                        ci_ser_low = ci_ser_high = 0.0
                        is_within_noise_ser = True

                    # 2. Time-Block Bootstrap (resample weekly review time blocks)
                    boot_diffs_time: list[float] = []
                    for _ in range(n_bootstrap):
                        w_idx = rng.integers(0, n_weeks, size=n_weeks)

                        b_fr_m, b_inv_m = [], []
                        for m in series_data_model:
                            s = m["week_sales"][w_idx].sum()
                            d = m["week_demand"][w_idx].sum()
                            b_fr_m.append((s / max(d, 1e-6)) * 100.0)
                            w_days = max(m["week_days"][w_idx].sum(), 1.0)
                            b_inv_m.append(m["week_inv_sum"][w_idx].sum() / w_days)

                        b_fr_s, b_inv_s = [], []
                        for m in series_data_snaive:
                            s = m["week_sales"][w_idx].sum()
                            d = m["week_demand"][w_idx].sum()
                            b_fr_s.append((s / max(d, 1e-6)) * 100.0)
                            w_days = max(m["week_days"][w_idx].sum(), 1.0)
                            b_inv_s.append(m["week_inv_sum"][w_idx].sum() / w_days)

                        if min(b_fr_m) <= target_fr <= max(b_fr_m) and min(
                            b_fr_s
                        ) <= target_fr <= max(b_fr_s):
                            im = np.argsort(b_fr_m)
                            is_ = np.argsort(b_fr_s)
                            bf_m = interp1d(np.array(b_fr_m)[im], np.array(b_inv_m)[im])
                            bf_s = interp1d(np.array(b_fr_s)[is_], np.array(b_inv_s)[is_])
                            b_diff = (
                                (float(bf_m(target_fr)) - float(bf_s(target_fr)))
                                / max(float(bf_s(target_fr)), 1e-6)
                            ) * 100.0
                            boot_diffs_time.append(b_diff)

                    if len(boot_diffs_time) >= 20:
                        ci_time_low = float(np.percentile(boot_diffs_time, 2.5))
                        ci_time_high = float(np.percentile(boot_diffs_time, 97.5))
                        is_within_noise_time = ci_time_low <= 0.0 <= ci_time_high
                    else:
                        ci_time_low = ci_time_high = 0.0
                        is_within_noise_time = True

                    results.append(
                        {
                            "lead_time_days": L,
                            "comparison": f"{model_label} vs Seasonal Naive",
                            "forecaster": model_label,
                            "target_fill_rate_pct": target_fr,
                            "is_reachable": True,
                            "required_inventory_lightgbm": float(round(req_inv_m, 2)),
                            "required_inventory_snaive": float(round(req_inv_sn, 2)),
                            "pct_difference": float(round(pct_diff, 2)),
                            "ci_95_series_pct_diff_low": float(round(ci_ser_low, 2)),
                            "ci_95_series_pct_diff_high": float(round(ci_ser_high, 2)),
                            "ci_95_time_block_pct_diff_low": float(round(ci_time_low, 2)),
                            "ci_95_time_block_pct_diff_high": float(round(ci_time_high, 2)),
                            "is_within_noise_series": is_within_noise_ser,
                            "is_within_noise_time_block": is_within_noise_time,
                            "interpretation": (
                                f"{model_label} vs S.Naive at {target_fr}% FR: "
                                f"{pct_diff:+.2f}% inventory "
                                f"(Series 95% CI: [{ci_ser_low:+.2f}%, {ci_ser_high:+.2f}%], "
                                f"Time-Block 95% CI: [{ci_time_low:+.2f}%, {ci_time_high:+.2f}%])"
                            ),
                        }
                    )

        return results

    def simulate_by_family_matched_fill_rate(
        self,
        frontier_df: pd.DataFrame | None = None,
        lead_times: tuple[int, ...] = (3, 7),
        target_fill_rates: tuple[float, ...] = (98.5, 99.0, 99.5),
        families: list[str] | None = None,
        n_bootstrap: int = 1000,
        seed: int = 42,
    ) -> list[dict[str, Any]]:
        """Compute per-family matched-fill-rate inventory comparison with bootstrap CIs.

        For each family and lead time, traces the fill-rate vs average-inventory frontier,
        interpolates required inventory at fixed fill rates, and computes 95% bootstrap CIs
        across stores. Targets unreachable on the empirical grid are reported without extrapolation.
        """
        rng = np.random.default_rng(seed)
        target_fams = families or [
            "GROCERY I",
            "BEVERAGES",
            "PRODUCE",
            "CLEANING",
            "DAIRY",
            "BREAD/BAKERY",
            "POULTRY",
            "MEATS",
            "DELI",
            "PERSONAL CARE",
            "BABY CARE",
            "BOOKS",
            "LAWN AND GARDEN",
        ]

        f_df = frontier_df if frontier_df is not None else self.run_frontier(lead_times=lead_times)

        family_series = self.series_keys["family"].to_numpy()
        results: list[dict[str, Any]] = []

        for fam in target_fams:
            fam_idx = np.where(family_series == fam)[0]
            if len(fam_idx) == 0:
                continue
            n_stores = len(fam_idx)

            for L in lead_times:
                df_l = f_df[f_df["lead_time_days"] == L]

                curves: dict[str, dict[str, Any]] = {}
                for pol in [
                    "lightgbm_p50_safety_stock",
                    "lightgbm_point_safety_stock",
                    "seasonal_naive_safety_stock",
                ]:
                    fr_list, inv_list, series_list = [], [], []
                    pol_rows = df_l[df_l["policy"] == pol]

                    for _, r in pol_rows.iterrows():
                        m = r["series_metrics"]
                        dem = float(m["demand"][fam_idx].sum())
                        sal = float(m["sales"][fam_idx].sum())
                        inv = float(m["inv_sum"][fam_idx].sum() / m["eval_days"])
                        fr = (sal / max(dem, 1e-6)) * 100.0
                        fr_list.append(fr)
                        inv_list.append(inv)
                        series_list.append(
                            {
                                "demand": m["demand"][fam_idx],
                                "sales": m["sales"][fam_idx],
                                "inv_sum": m["inv_sum"][fam_idx],
                                "eval_days": m["eval_days"],
                                "fam_week_sales": (
                                    m["series_week_sales"][fam_idx].sum(axis=0)
                                    if "series_week_sales" in m
                                    else np.zeros(m.get("n_weeks", 1))
                                ),
                                "fam_week_demand": (
                                    m["series_week_demand"][fam_idx].sum(axis=0)
                                    if "series_week_demand" in m
                                    else np.zeros(m.get("n_weeks", 1))
                                ),
                                "fam_week_inv": (
                                    m["series_week_inv"][fam_idx].sum(axis=0)
                                    if "series_week_inv" in m
                                    else np.zeros(m.get("n_weeks", 1))
                                ),
                                "week_days": m.get("week_days", np.ones(m.get("n_weeks", 1))),
                                "n_weeks": m.get("n_weeks", 1),
                            }
                        )

                    curves[pol] = {
                        "fr": np.array(fr_list),
                        "inv": np.array(inv_list),
                        "series": series_list,
                        "min_fr": float(min(fr_list)) if fr_list else 0.0,
                        "max_fr": float(max(fr_list)) if fr_list else 0.0,
                    }

                c_p50 = curves["lightgbm_p50_safety_stock"]
                c_pt = curves["lightgbm_point_safety_stock"]
                c_sn = curves["seasonal_naive_safety_stock"]

                for target_fr in target_fill_rates:
                    reach_p50 = c_p50["min_fr"] <= target_fr <= c_p50["max_fr"]
                    reach_pt = c_pt["min_fr"] <= target_fr <= c_pt["max_fr"]
                    reach_sn = c_sn["min_fr"] <= target_fr <= c_sn["max_fr"]

                    entry: dict[str, Any] = {
                        "family": fam,
                        "lead_time_days": L,
                        "target_fill_rate_pct": target_fr,
                        "max_fill_rate_p50": round(c_p50["max_fr"], 2),
                        "max_fill_rate_point": round(c_pt["max_fr"], 2),
                        "max_fill_rate_snaive": round(c_sn["max_fr"], 2),
                        "is_reachable_p50": reach_p50 and reach_sn,
                        "is_reachable_point": reach_pt and reach_sn,
                        "grid_fr_range_p50": (
                            round(c_p50["min_fr"], 2),
                            round(c_p50["max_fr"], 2),
                        ),
                        "grid_fr_range_point": (
                            round(c_pt["min_fr"], 2),
                            round(c_pt["max_fr"], 2),
                        ),
                        "grid_fr_range_snaive": (
                            round(c_sn["min_fr"], 2),
                            round(c_sn["max_fr"], 2),
                        ),
                    }

                    # Shared Seasonal Naive interpolation if reachable
                    if reach_sn:
                        ip_sn = np.argsort(c_sn["fr"])
                        f_sn = interp1d(c_sn["fr"][ip_sn], c_sn["inv"][ip_sn])
                        req_sn = float(f_sn(target_fr))
                    else:
                        req_sn = None

                    # 1. P50 comparison
                    if reach_p50 and reach_sn and req_sn is not None:
                        ip_p50 = np.argsort(c_p50["fr"])
                        f_p50 = interp1d(c_p50["fr"][ip_p50], c_p50["inv"][ip_p50])
                        req_p50 = float(f_p50(target_fr))
                        pct_diff_p50 = ((req_p50 - req_sn) / max(req_sn, 1e-6)) * 100.0

                        # A. Store series bootstrap (resample stores within family)
                        b_diffs_ser: list[float] = []
                        for _ in range(n_bootstrap):
                            b_idx = rng.integers(0, n_stores, size=n_stores)
                            b_fr_m, b_inv_m = [], []
                            for m in c_p50["series"]:
                                s = m["sales"][b_idx].sum()
                                d = m["demand"][b_idx].sum()
                                b_fr_m.append((s / max(d, 1e-6)) * 100.0)
                                b_inv_m.append(m["inv_sum"][b_idx].sum() / m["eval_days"])

                            b_fr_s, b_inv_s = [], []
                            for m in c_sn["series"]:
                                s = m["sales"][b_idx].sum()
                                d = m["demand"][b_idx].sum()
                                b_fr_s.append((s / max(d, 1e-6)) * 100.0)
                                b_inv_s.append(m["inv_sum"][b_idx].sum() / m["eval_days"])

                            if min(b_fr_m) <= target_fr <= max(b_fr_m) and min(
                                b_fr_s
                            ) <= target_fr <= max(b_fr_s):
                                im = np.argsort(b_fr_m)
                                is_ = np.argsort(b_fr_s)
                                bf_p = interp1d(np.array(b_fr_m)[im], np.array(b_inv_m)[im])
                                bf_s = interp1d(np.array(b_fr_s)[is_], np.array(b_inv_s)[is_])
                                diff = (
                                    (float(bf_p(target_fr)) - float(bf_s(target_fr)))
                                    / max(float(bf_s(target_fr)), 1e-6)
                                ) * 100.0
                                b_diffs_ser.append(diff)

                        # B. Time-block bootstrap (resample weeks within family)
                        n_w = c_p50["series"][0]["n_weeks"]
                        b_diffs_time: list[float] = []
                        for _ in range(n_bootstrap):
                            w_idx = rng.integers(0, n_w, size=n_w)
                            b_fr_m, b_inv_m = [], []
                            for m in c_p50["series"]:
                                s = m["fam_week_sales"][w_idx].sum()
                                d = m["fam_week_demand"][w_idx].sum()
                                b_fr_m.append((s / max(d, 1e-6)) * 100.0)
                                w_d = max(m["week_days"][w_idx].sum(), 1.0)
                                b_inv_m.append(m["fam_week_inv"][w_idx].sum() / w_d)

                            b_fr_s, b_inv_s = [], []
                            for m in c_sn["series"]:
                                s = m["fam_week_sales"][w_idx].sum()
                                d = m["fam_week_demand"][w_idx].sum()
                                b_fr_s.append((s / max(d, 1e-6)) * 100.0)
                                w_d = max(m["week_days"][w_idx].sum(), 1.0)
                                b_inv_s.append(m["fam_week_inv"][w_idx].sum() / w_d)

                            if min(b_fr_m) <= target_fr <= max(b_fr_m) and min(
                                b_fr_s
                            ) <= target_fr <= max(b_fr_s):
                                im = np.argsort(b_fr_m)
                                is_ = np.argsort(b_fr_s)
                                bf_p = interp1d(np.array(b_fr_m)[im], np.array(b_inv_m)[im])
                                bf_s = interp1d(np.array(b_fr_s)[is_], np.array(b_inv_s)[is_])
                                diff = (
                                    (float(bf_p(target_fr)) - float(bf_s(target_fr)))
                                    / max(float(bf_s(target_fr)), 1e-6)
                                ) * 100.0
                                b_diffs_time.append(diff)

                        ci_ser_low = (
                            float(np.percentile(b_diffs_ser, 2.5))
                            if len(b_diffs_ser) >= 20
                            else 0.0
                        )
                        ci_ser_high = (
                            float(np.percentile(b_diffs_ser, 97.5))
                            if len(b_diffs_ser) >= 20
                            else 0.0
                        )
                        ci_time_low = (
                            float(np.percentile(b_diffs_time, 2.5))
                            if len(b_diffs_time) >= 20
                            else 0.0
                        )
                        ci_time_high = (
                            float(np.percentile(b_diffs_time, 97.5))
                            if len(b_diffs_time) >= 20
                            else 0.0
                        )

                        excl_ser = ci_ser_low > 0 or ci_ser_high < 0
                        excl_time = ci_time_low > 0 or ci_time_high < 0
                        is_win = excl_ser and excl_time and pct_diff_p50 < 0

                        entry.update(
                            {
                                "required_inventory_lightgbm_p50": float(round(req_p50, 2)),
                                "required_inventory_snaive": float(round(req_sn, 2)),
                                "pct_diff_p50_vs_snaive": float(round(pct_diff_p50, 2)),
                                "ci_95_p50_low": float(round(ci_ser_low, 2)),
                                "ci_95_p50_high": float(round(ci_ser_high, 2)),
                                "ci_95_series_p50_low": float(round(ci_ser_low, 2)),
                                "ci_95_series_p50_high": float(round(ci_ser_high, 2)),
                                "ci_95_time_block_p50_low": float(round(ci_time_low, 2)),
                                "ci_95_time_block_p50_high": float(round(ci_time_high, 2)),
                                "p50_ci_excludes_zero": excl_ser and excl_time,
                                "is_within_noise_series_p50": not excl_ser,
                                "is_within_noise_time_block_p50": not excl_time,
                                "is_statistically_significant_win_p50": is_win,
                            }
                        )
                    else:
                        entry.update(
                            {
                                "required_inventory_lightgbm_p50": None,
                                "required_inventory_snaive": (
                                    float(round(req_sn, 2)) if req_sn is not None else None
                                ),
                                "pct_diff_p50_vs_snaive": None,
                                "ci_95_p50_low": None,
                                "ci_95_p50_high": None,
                                "ci_95_series_p50_low": None,
                                "ci_95_series_p50_high": None,
                                "ci_95_time_block_p50_low": None,
                                "ci_95_time_block_p50_high": None,
                                "p50_ci_excludes_zero": False,
                                "is_within_noise_series_p50": True,
                                "is_within_noise_time_block_p50": True,
                                "is_statistically_significant_win_p50": False,
                            }
                        )

                    # 2. Point comparison
                    if reach_pt and reach_sn and req_sn is not None:
                        ip_pt = np.argsort(c_pt["fr"])
                        f_pt = interp1d(c_pt["fr"][ip_pt], c_pt["inv"][ip_pt])
                        req_pt = float(f_pt(target_fr))
                        pct_diff_pt = ((req_pt - req_sn) / max(req_sn, 1e-6)) * 100.0

                        # A. Store series bootstrap
                        b_diffs_pt_ser: list[float] = []
                        for _ in range(n_bootstrap):
                            b_idx = rng.integers(0, n_stores, size=n_stores)
                            b_fr_m, b_inv_m = [], []
                            for m in c_pt["series"]:
                                s = m["sales"][b_idx].sum()
                                d = m["demand"][b_idx].sum()
                                b_fr_m.append((s / max(d, 1e-6)) * 100.0)
                                b_inv_m.append(m["inv_sum"][b_idx].sum() / m["eval_days"])

                            b_fr_s, b_inv_s = [], []
                            for m in c_sn["series"]:
                                s = m["sales"][b_idx].sum()
                                d = m["demand"][b_idx].sum()
                                b_fr_s.append((s / max(d, 1e-6)) * 100.0)
                                b_inv_s.append(m["inv_sum"][b_idx].sum() / m["eval_days"])

                            if min(b_fr_m) <= target_fr <= max(b_fr_m) and min(
                                b_fr_s
                            ) <= target_fr <= max(b_fr_s):
                                im = np.argsort(b_fr_m)
                                is_ = np.argsort(b_fr_s)
                                bf_p = interp1d(np.array(b_fr_m)[im], np.array(b_inv_m)[im])
                                bf_s = interp1d(np.array(b_fr_s)[is_], np.array(b_inv_s)[is_])
                                diff = (
                                    (float(bf_p(target_fr)) - float(bf_s(target_fr)))
                                    / max(float(bf_s(target_fr)), 1e-6)
                                ) * 100.0
                                b_diffs_pt_ser.append(diff)

                        # B. Time-block bootstrap
                        n_w = c_pt["series"][0]["n_weeks"]
                        b_diffs_pt_time: list[float] = []
                        for _ in range(n_bootstrap):
                            w_idx = rng.integers(0, n_w, size=n_w)
                            b_fr_m, b_inv_m = [], []
                            for m in c_pt["series"]:
                                s = m["fam_week_sales"][w_idx].sum()
                                d = m["fam_week_demand"][w_idx].sum()
                                b_fr_m.append((s / max(d, 1e-6)) * 100.0)
                                w_d = max(m["week_days"][w_idx].sum(), 1.0)
                                b_inv_m.append(m["fam_week_inv"][w_idx].sum() / w_d)

                            b_fr_s, b_inv_s = [], []
                            for m in c_sn["series"]:
                                s = m["fam_week_sales"][w_idx].sum()
                                d = m["fam_week_demand"][w_idx].sum()
                                b_fr_s.append((s / max(d, 1e-6)) * 100.0)
                                w_d = max(m["week_days"][w_idx].sum(), 1.0)
                                b_inv_s.append(m["fam_week_inv"][w_idx].sum() / w_d)

                            if min(b_fr_m) <= target_fr <= max(b_fr_m) and min(
                                b_fr_s
                            ) <= target_fr <= max(b_fr_s):
                                im = np.argsort(b_fr_m)
                                is_ = np.argsort(b_fr_s)
                                bf_p = interp1d(np.array(b_fr_m)[im], np.array(b_inv_m)[im])
                                bf_s = interp1d(np.array(b_fr_s)[is_], np.array(b_inv_s)[is_])
                                diff = (
                                    (float(bf_p(target_fr)) - float(bf_s(target_fr)))
                                    / max(float(bf_s(target_fr)), 1e-6)
                                ) * 100.0
                                b_diffs_pt_time.append(diff)

                        ci_pt_ser_low = (
                            float(np.percentile(b_diffs_pt_ser, 2.5))
                            if len(b_diffs_pt_ser) >= 20
                            else 0.0
                        )
                        ci_pt_ser_high = (
                            float(np.percentile(b_diffs_pt_ser, 97.5))
                            if len(b_diffs_pt_ser) >= 20
                            else 0.0
                        )
                        ci_pt_time_low = (
                            float(np.percentile(b_diffs_pt_time, 2.5))
                            if len(b_diffs_pt_time) >= 20
                            else 0.0
                        )
                        ci_pt_time_high = (
                            float(np.percentile(b_diffs_pt_time, 97.5))
                            if len(b_diffs_pt_time) >= 20
                            else 0.0
                        )

                        excl_pt_ser = ci_pt_ser_low > 0 or ci_pt_ser_high < 0
                        excl_pt_time = ci_pt_time_low > 0 or ci_pt_time_high < 0
                        is_win_pt = excl_pt_ser and excl_pt_time and pct_diff_pt < 0

                        entry.update(
                            {
                                "required_inventory_lightgbm_point": float(round(req_pt, 2)),
                                "pct_diff_point_vs_snaive": float(round(pct_diff_pt, 2)),
                                "ci_95_series_point_low": float(round(ci_pt_ser_low, 2)),
                                "ci_95_series_point_high": float(round(ci_pt_ser_high, 2)),
                                "ci_95_time_block_point_low": float(round(ci_pt_time_low, 2)),
                                "ci_95_time_block_point_high": float(round(ci_pt_time_high, 2)),
                                "point_ci_excludes_zero": excl_pt_ser and excl_pt_time,
                                "is_within_noise_series_point": not excl_pt_ser,
                                "is_within_noise_time_block_point": not excl_pt_time,
                                "is_statistically_significant_win_point": is_win_pt,
                            }
                        )
                    else:
                        entry.update(
                            {
                                "required_inventory_lightgbm_point": None,
                                "pct_diff_point_vs_snaive": None,
                                "ci_95_series_point_low": None,
                                "ci_95_series_point_high": None,
                                "ci_95_time_block_point_low": None,
                                "ci_95_time_block_point_high": None,
                                "point_ci_excludes_zero": False,
                                "is_within_noise_series_point": True,
                                "is_within_noise_time_block_point": True,
                                "is_statistically_significant_win_point": False,
                            }
                        )

                    results.append(entry)

        return results

